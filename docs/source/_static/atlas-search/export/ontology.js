// Converters for BrainGlobe terminologies (ontologies).
//
// Input rows (from the index builder) look like
//   {id, parent, value, name, acronym, color: "#RRGGBB", path: [ids]}
// where `value` is the integer stored in the annotation volume.

export function hexToRgb(hex) {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex || "");
  if (!m) return [255, 255, 255];
  const n = parseInt(m[1], 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/** BrainGlobe v1-style structures.json (list of structure dicts). */
export function toStructuresJson(rows) {
  return JSON.stringify(
    rows.map((r) => ({
      acronym: r.acronym,
      id: r.id,
      annotation_value: r.value,
      name: r.name,
      structure_id_path: r.path,
      rgb_triplet: hexToRgb(r.color),
    })),
    null,
    2,
  );
}

/** Largest label value ITK-SNAP can represent (labels are 16-bit). */
export const ITKSNAP_MAX_LABEL = 65535;

/**
 * ITK-SNAP label description file. Values are written unchanged; labels
 * above ITKSNAP_MAX_LABEL cannot be represented by ITK-SNAP and are written
 * as commented-out lines so the file still loads.
 */
export function toItkSnap(rows) {
  const out = [
    "################################################",
    "# ITK-SnAP Label Description File",
    "# Generated by brainglobe-search",
    "# Fields:",
    "#    IDX:   Zero-based index",
    "#    -R-:   Red color component (0..255)",
    "#    -G-:   Green color component (0..255)",
    "#    -B-:   Blue color component (0..255)",
    "#    -A-:   Label transparency (0.00 .. 1.00)",
    "#    VIS:   Label visibility (0 or 1)",
    "#    IDX:   Label mesh visibility (0 or 1)",
    "#  LABEL:   Label description",
    "################################################",
    '    0     0    0    0        0  0  0    "Clear Label"',
  ];
  for (const r of rows) {
    if (r.value == null || r.value === 0) continue;
    const [R, G, B] = hexToRgb(r.color);
    const label = `${r.name} (${r.acronym})`.replace(/"/g, "'");
    const comment = r.value > ITKSNAP_MAX_LABEL ? "#" : "";
    out.push(
      `${comment}${String(r.value).padStart(5)} ${String(R).padStart(5)} ${String(G).padStart(4)} ${String(B).padStart(4)}        1  1  1    "${label}"`,
    );
  }
  return out.join("\n") + "\n";
}

/** 3D Slicer color table (.ctbl). Names cannot contain spaces. */
export function toSlicerCtbl(rows) {
  const out = ["# Color table file generated by brainglobe-search", `# ${rows.length} values`];
  out.push("0 background 0 0 0 0");
  for (const r of rows) {
    if (r.value == null || r.value === 0) continue;
    const [R, G, B] = hexToRgb(r.color);
    const name = (r.acronym || r.name).replace(/\s+/g, "_");
    out.push(`${r.value} ${name} ${R} ${G} ${B} 255`);
  }
  return out.join("\n") + "\n";
}

/** Build a parent->children map and return root rows. */
export function buildTree(rows) {
  const byId = new Map(rows.map((r) => [r.id, { ...r, children: [] }]));
  const roots = [];
  for (const node of byId.values()) {
    const p = node.parent != null ? byId.get(node.parent) : null;
    if (p) p.children.push(node);
    else roots.push(node);
  }
  return roots;
}
